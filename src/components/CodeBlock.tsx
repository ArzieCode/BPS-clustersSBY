import React, {useMemo, useState} from 'react';
import hljs from 'highlight.js/lib/core';
import python from 'highlight.js/lib/languages/python';

hljs.registerLanguage('python', python);

interface CodeBlockProps {
  code: string;
  isAutoGenerated?: boolean;
  onSaveCode?: (nextCode: string) => void;
  compact?: boolean;
}

export const CodeBlock: React.FC<CodeBlockProps> = ({
  code,
  isAutoGenerated = false,
  onSaveCode,
  compact = false,
}) => {
  const [copied, setCopied] = useState(false);
  const [editing, setEditing] = useState(false);
  const [draft, setDraft] = useState(code);

  const highlightedLines = useMemo(() => {
    const rawLines = code.split('\n');
    return rawLines.map((line) => {
      try {
        return hljs.highlight(line, {language: 'python'}).value || '&nbsp;';
      } catch {
        return line
          .replace(/&/g, '&amp;')
          .replace(/</g, '&lt;')
          .replace(/>/g, '&gt;');
      }
    });
  }, [code]);

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(code);
      setCopied(true);
      setTimeout(() => setCopied(false), 1800);
    } catch {
      // Fallback ignored
    }
  };

  const handleStartEdit = () => {
    setDraft(code);
    setEditing(true);
  };

  const handleSave = () => {
    if (onSaveCode) {
      onSaveCode(draft);
    }
    setEditing(false);
  };

  return (
    <div className="border border-[var(--rule-strong)] bg-[var(--paper-alt)]">
      {/* Toolbar */}
      <div className="flex flex-wrap items-center justify-between gap-2 px-3 py-2 border-b border-[var(--rule)] bg-[var(--paper)]">
        <div className="flex items-center gap-3 text-[12px] font-mono-code">
          <span className="small-caps tracking-widest font-semibold text-[var(--ink)]">
            Python
          </span>
          {isAutoGenerated && (
            <span className="text-[11px] italic text-[var(--ink-subtle)]">
              (kode otomatis, mohon diperiksa)
            </span>
          )}
        </div>

        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={handleCopy}
            className="px-2.5 py-1 text-[12px] font-mono-code border border-[var(--rule)] bg-[var(--paper)] text-[var(--ink)] hover:border-[var(--rule-strong)] cursor-pointer fade-150"
          >
            {copied ? 'Tersalin' : 'Salin'}
          </button>
          {onSaveCode && !editing && (
            <button
              type="button"
              onClick={handleStartEdit}
              className="px-2.5 py-1 text-[12px] font-mono-code border border-[var(--rule)] bg-[var(--paper)] text-[var(--ink)] hover:border-[var(--rule-strong)] cursor-pointer fade-150"
            >
              Ubah
            </button>
          )}
        </div>
      </div>

      {/* Editor or Highlighted code with line numbers */}
      {editing ? (
        <div className="p-3 space-y-2">
          <textarea
            value={draft}
            onChange={(e) => setDraft(e.target.value)}
            rows={Math.max(10, draft.split('\n').length + 1)}
            className="w-full p-3 font-mono-code text-[13px] leading-relaxed border border-[var(--rule-strong)] bg-[var(--paper)] text-[var(--ink)]"
            aria-label="Sunting kode Python"
          />
          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={handleSave}
              className="px-3 py-1.5 text-[12px] font-mono-code border border-[var(--rule-strong)] bg-[var(--ink)] text-[var(--paper)] cursor-pointer"
            >
              Simpan Perubahan
            </button>
            <button
              type="button"
              onClick={() => setEditing(false)}
              className="px-3 py-1.5 text-[12px] font-mono-code border border-[var(--rule)] bg-[var(--paper)] text-[var(--ink)] cursor-pointer"
            >
              Batal
            </button>
          </div>
        </div>
      ) : (
        <div
          className={`overflow-x-auto hljs-mono font-mono-code ${
            compact ? 'text-[12px] leading-[1.55]' : 'text-[13px] leading-[1.6]'
          } py-2`}
        >
          <table className="w-full border-collapse">
            <tbody>
              {highlightedLines.map((html, idx) => (
                <tr key={idx} className="hover:bg-[var(--paper)]">
                  <td
                    className="select-none text-right pr-3 pl-3 text-[var(--ink-subtle)] border-r border-[var(--rule)] w-[1%] whitespace-nowrap tabular-nums align-top"
                    aria-hidden="true"
                  >
                    {idx + 1}
                  </td>
                  <td
                    className="pl-3 pr-4 whitespace-pre align-top"
                    dangerouslySetInnerHTML={{__html: html}}
                  />
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
};
